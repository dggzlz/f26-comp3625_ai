# standard way of keeping randomness the same at every run
np.random.seed(42)

THRESHOLD = 0.50          # Logistic Regression threshold
SPLIT_TRAIN = 0.60        # 60% training
SPLIT_VALID = 0.50        # 50/50 on remaining data after train split
COVER_LIMIT = 100_000_000 # Max. budget for coverage

def eval_profit(model, test_sets: tuple, limit=COVER_LIMIT):
    """
    Evaluates the financial performance of a trained model on testing data 
    by calculating total profit, capped by a maximum cumulative coverage limit.

    Parameters:
    model : LogisticRegression - The trained classification model.
    test_sets : tuple - A tuple containing (x_test, y_test) data splits.
    limit : int - The maximum cumulative coverage amount the company is willing to underwrite.

    Returns:
    float - The total net profit (premiums collected minus claims paid) for the selected portfolio.
    """
    x_test, y_test = test_sets
    
    # Generate claim probabilities and calculate proposed premiums
    p_claims = model.predict_proba(x_test)
    coverage = x_test['coverage_amount'].to_numpy()
    premium, viable = set_premiums(p_claims, coverage)

    # Filter arrays to only include policies that are economically viable for both parties 
    # (v as viable)
    v_coverage = coverage[viable]
    v_premium = premium[viable]
    v_p_claims = p_claims[viable]

    # Calculate profit margin per customer to prioritize the most lucrative policies
    profit_margin = (v_premium - (v_p_claims * v_coverage)) / v_coverage
    
    # Sort customers by profit margin in descending order
    idx = np.argsort(profit_margin)[::-1]
    
    # Select top customers until the cumulative coverage hits the $100M company limit
    profitable_customers = np.cumsum(v_coverage[idx]) <= limit
    
    # Sum up the actual premiums collected from the accepted customers
    money_in = v_premium[idx][profitable_customers].sum()
    
    # Filter actual viable customers
    actual_filtered = (((y_test.to_numpy())[viable])[idx]) 
    
    # Select only profitable customer
    actual_profitable = actual_filtered[profitable_customers]
    
    # Get the policy payout amounts for the accepted customers
    payout_amt = v_coverage[idx][profitable_customers]
    
    # Sum up the actual payouts based on the ground-truth claims (y_test)
    money_out = (actual_profitable * payout_amt).sum()
    
    # return actual profit
    return money_in - money_out    

def train_and_eval(params, train_set, test_set):
    """
    Wrapper function for Simulated Annealing to train a model with a specific 
    set of hyperparameters and evaluate its resulting financial performance.

    Parameters:
    params : tuple or np.array - The hyperparameters (epochs, alpha) to test.
    train_set : tuple - A tuple containing (x_train, y_train) data splits.
    test_set : tuple - A tuple containing (x_test, y_test) data splits.

    Returns:
    float - The total profit generated by the model using these parameters.
    """
    epochs, alpha = params
    x_train, y_train = train_set

    # Instantiate and train the model using the candidate hyperparameters
    model = LogisticRegression((int(epochs), alpha))
    model.fit(x_train, y_train)
    return eval_profit(model, test_set)

def get_metrics(probs, actual):
    """
    Evaluates the performance of a binary classification model using a default 0.50 probability threshold.

    Parameters:
    probs: np.ndarray - An array of predicted probabilities (floats between 0.0 and 1.0) output by the model.
    actual: np.ndarray - An boolean or integer array of true class labels (1 for claim, 0 for no claim).
    """
    
    # Convert probabilities to binary predictions based on standard Logistic Regression threshold
    prediction = probs >= THRESHOLD
    actual = actual.astype(bool)
    
    # Calculate confusion matrix components using vectorized bitwise operations
    TP = prediction & actual     # True Positive: Predicted 1, Actual 1
    TN = ~(prediction | actual)  # True Negative: Predicted 0, Actual 0
    FP = prediction & ~actual    # False Positive: Predicted 1, Actual 0
    FN = ~prediction & actual    # False Negative: Predicted 0, Actual 1

    # Calculate final percentages using .mean() and .sum() to aggregate the boolean arrays
    # Update global variables
    acc = (prediction == actual).mean()
    sens = TP.sum() / (TP + FN).sum()
    spec = TN.sum() / (TN + FP).sum()
    
    return acc, sens, spec

def save_model(model):
    """
    Serializes the fully trained Logistic Regression model to a binary file.

    Parameters:
    model : LogisticRegression - The optimized model object to save.
    """
    os.makedirs("./model", exist_ok=True)
    with open("./model/final_model.pkl", "wb") as f:
        pickle.dump(model, f)

def print_stats(model_title, hyperparams, profit, probs, y_class):
    """Helper function to print models stats"""
    
    accuracy, sensitivity, specificity = get_metrics(probs, y_class)
    
    print(f"\n{model_title}'s performance")
    print("=" * 50)
    print(f"Accuracy = {accuracy:.2%}")
    print(f"Sensitivity = {sensitivity:.2%}")
    print(f"Specificity = {specificity:.2%}")
    print("-"* 50)
    print("Hyperparameters:", hyperparams)
    print(f"Profit: {profit:,.2f}")
    print("=" * 50)
    
